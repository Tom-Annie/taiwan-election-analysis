def seed_legislative_election(data: dict):
    # 避免重複匯入
    existing = db.query(Election).filter(
        Election.year == data["year"],
        Election.type == "legislative",
    ).first()
    if existing:
        print(f"  [SKIP] {data['year']} 屆立委選舉已存在，略過。")
        return

    election = Election(
        year=data["year"],
        type="legislative",
        name=data["name"],
        date=data["date"],
        total_voters=None,
        total_votes=None,
        turnout_rate=None,
    )
    db.add(election)
    db.flush()

    for num, party, total_seats, pr_vote_rate, detail in data["candidates"]:
        c = Candidate(
            election_id=election.id,
            number=num,
            name=f"{party} 不分區",   # 以「黨名 不分區」作為記錄名稱
            party=party,
            vice_name=detail,           # 席次明細
            total_votes=total_seats,    # 總席次
            vote_rate=pr_vote_rate,     # 不分區政黨得票率 (%)
            elected=1,                  # 所有進入國會的黨均為當選
        )
        db.add(c)

    db.commit()
    print(f"  [OK]   {data['year']} 屆立委選舉已建立 "
          f"({len(data['candidates'])} 黨，共 {data['total_seats']} 席)")


