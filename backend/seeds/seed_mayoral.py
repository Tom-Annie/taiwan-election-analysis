def seed_mayoral(data: dict):
    existing = db.query(Election).filter(
        Election.year == data["year"],
        Election.type == "local",
    ).first()
    if existing:
        print(f"  [skip] {data['year']} local election already exists")
        return

    election = Election(
        year=data["year"],
        type="local",
        name=data["name"],
        date=data["date"],
        total_voters=data["total_voters"],
        total_votes=data["total_votes"],
        turnout_rate=data["turnout"],
    )
    db.add(election)
    db.flush()

    for region_code, candidates in data["races"].items():
        region = db.query(Region).filter(Region.code == region_code).first()
        if not region:
            continue

        region_total = sum(c[2] for c in candidates)
        for name, party, votes, rate, elected in candidates:
            c = Candidate(
                election_id=election.id,
                number=None,
                name=name,
                party=party,
                vice_name=None,
                total_votes=votes,
                vote_rate=rate,
                elected=elected,
            )
            db.add(c)
            db.flush()

            db.add(RegionResult(
                election_id=election.id,
                region_code=region_code,
                candidate_id=c.id,
                votes=votes,
                vote_rate=rate,
                turnout_rate=data["turnout"],
            ))

    db.commit()
    print(f"  [done] {data['year']} — {len(data['races'])} races")


print("Seeding mayoral elections...")
for e_data in MAYORAL_ELECTIONS:
    seed_mayoral(e_data)

db.close()
print("Mayoral seed data loaded!")
